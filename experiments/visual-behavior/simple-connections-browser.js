async page => {
  const check=(value,message)=>{if(!value)throw Error(message);},errors=[],checks=[];
  page.on('pageerror',error=>errors.push(error.message));
  const origin=await page.evaluate(()=>location.origin);
  await page.goto(origin);await page.setViewportSize({width:1440,height:1000});
  await page.waitForFunction(()=>window.duckflyTelemetry?.ready,null,{timeout:60000});
  await page.getByRole('button',{name:'Open studio',exact:true}).click();
  await page.locator('[data-scenario="target"]').click();
  await page.getByRole('button',{name:'Continue →',exact:true}).click();
  const wizard=page.locator('#scene-setup');
  check(await wizard.locator('.trigger-connections').count()===1,'Wizard has competing connection editors');
  check(!/default connections|custom connections/i.test(await wizard.innerText()),'Old routing modes are still exposed');
  check(await wizard.locator('[data-connection="enabled"]').count()===0,'Hidden master switch still exists');
  check(await wizard.locator('#setup-forward option[value="look-left"]').count()===1,'Walking response cannot be reassigned directly to a head action');
  check(!await wizard.locator('[data-setup-panel="advanced-brain"]').evaluate(el=>el.open),'Input settings crowd the first view');
  for(const width of [1440,1280,390,320]){
    await page.setViewportSize({width,height:width<500?844:1000});
    check(await wizard.evaluate(el=>el.scrollWidth<=el.clientWidth+1),'Wizard overflows at '+width);
    await page.screenshot({path:`output/playwright/simple-connections-wizard-${width}.png`});
  }
  await page.setViewportSize({width:1440,height:1000});
  await wizard.locator('.connection-composer > summary').click();
  check(await wizard.getByRole('button',{name:'Add connection',exact:true}).isDisabled(),'A blank connection can be added');
  check(await wizard.locator('[data-connection="draft-trigger"] option').count()===14,'Not all 13 signals are available');
  check(await wizard.locator('[data-connection="draft-action"] option').count()===11,'Not all 10 actions are available');
  await wizard.getByLabel('New signal',{exact:true}).selectOption('forward');
  await wizard.getByLabel('New action',{exact:true}).selectOption('look-left');
  await wizard.getByRole('button',{name:'Add connection',exact:true}).click();
  check(await wizard.locator('#setup-forward').inputValue()==='walk','Adding a response removed the walker');
  check(await wizard.locator('#setup-turn').inputValue()==='follow','Adding a response removed steering');
  check(await wizard.locator('.connection-rule').count()===3,'Added response is not in the same list');
  await wizard.locator('[data-rule="connection-1"] summary').click();
  await wizard.getByLabel('Threshold 1',{exact:true}).fill('8');
  await page.getByRole('button',{name:'Continue →',exact:true}).click();
  await page.getByRole('button',{name:'Continue →',exact:true}).click();
  await page.getByRole('button',{name:'Start scene',exact:true}).click();
  await page.waitForFunction(()=>window.duckflyTelemetry.time>2,null,{timeout:45000});
  await page.locator('#pause').click();await page.waitForFunction(()=>window.duckflyTelemetry.paused);
  let state=await page.evaluate(()=>window.duckflyTelemetry),duck=state.scene.ducks[0];
  check(state.scene.version===8&&duck.connections.includeBrainMapping,'Added connection did not retain the scene behavior');
  check(duck.connections.rules[0].threshold===8,'Numeric edit was lost on Continue');
  check(state.ducks[0].distance>.05&&!state.ducks[0].fallen,'Adding a head response broke physical walking');
  checks.push({name:'wizard add preserves walker and steering',distance:state.ducks[0].distance,version:state.scene.version});
  await page.locator('#panel-connections').click();
  const editor=page.locator('#brain-mapping-panel');
  check(await editor.locator('.trigger-connections').count()===1,'Live editor has competing connection lists');
  check(await editor.locator('[data-rule="connection-1"] [data-connection="action"]').inputValue()==='look-left','Wizard and editor disagree');
  await editor.locator('[data-rule="connection-1"] summary').click();
  await editor.getByLabel('Threshold 1',{exact:true}).fill('9');
  await editor.locator('.connection-composer > summary').click();
  await editor.getByLabel('New signal',{exact:true}).selectOption('lost');
  await editor.getByLabel('New action',{exact:true}).selectOption('look-right');
  await editor.getByRole('button',{name:'Add connection',exact:true}).click();
  await page.waitForFunction(()=>window.duckflyTelemetry.scene.ducks[0].connections.rules.length===2);
  check(await page.evaluate(()=>window.duckflyTelemetry.scene.ducks[0].connections.rules[0].threshold===9),'Numeric blur detached the Add flow');
  await editor.locator('[data-rule="connection-2"] [data-connection="remove"]').click();
  await page.waitForFunction(()=>window.duckflyTelemetry.scene.ducks[0].connections.rules.length===1);
  await editor.locator('#mapping-forward').selectOption('look-right');
  await page.waitForFunction(()=>window.duckflyTelemetry.scene.ducks[0].mapping.forward==='off');
  check(await editor.locator('[data-rule="brain-forward-1"] [data-connection="action"]').inputValue()==='look-right','Direct remap did not create an editable signal connection');
  check(await editor.locator('#mapping-turn').inputValue()==='follow','Direct remap changed unrelated steering');
  await editor.locator('[data-rule="brain-forward-1"] [data-connection="remove"]').click();
  await editor.locator('#mapping-forward').selectOption('walk');
  await editor.locator('[data-rule="connection-1"] [data-connection="trigger"]').selectOption('seen');
  await editor.locator('[data-rule="connection-1"] [data-connection="action"]').selectOption('stop');
  await page.locator('#pause').click();
  await page.waitForFunction(()=>window.duckflyTelemetry.event?.causes[0]?.connections?.paused&&window.duckflyTelemetry.ducks[0].command.every(v=>v===0),null,{timeout:30000});
  await page.locator('#pause').click();await page.waitForFunction(()=>window.duckflyTelemetry.paused);
  checks.push({name:'live add, remove and direct remap; pause overrides original walking',passed:true});
  await editor.locator('[data-rule="connection-1"] [data-connection="rule-enabled"]').uncheck();
  await page.waitForFunction(()=>!window.duckflyTelemetry.scene.ducks[0].connections.rules[0].enabled);
  check(await editor.locator('[data-connection-live="connection-1"]').innerText()==='Off','Disabled response has misleading live activity');
  await editor.locator('.mapping-options > summary').click();
  await editor.locator('#mapping-controller').selectOption('manual');
  await page.waitForFunction(()=>window.duckflyTelemetry.scene.ducks[0].mode==='manual');
  check(await editor.locator('#mapping-forward').isDisabled(),'Manual mode still offers active-looking connections');
  await editor.getByRole('button',{name:'Use fly connections',exact:true}).click();
  await page.waitForFunction(()=>window.duckflyTelemetry.scene.ducks[0].mode==='target');
  check(await editor.locator('#mapping-forward').inputValue()==='walk','Returning to the fly lost the mapping');
  await editor.locator('.mapping-options > summary').click();
  for(const width of [1440,390,320]){
    await page.setViewportSize({width,height:width<500?844:1000});
    check(await editor.evaluate(el=>el.scrollWidth<=el.clientWidth+1),'Editor overflows at '+width);
    await page.screenshot({path:`output/playwright/simple-connections-editor-${width}.png`});
  }
  await page.setViewportSize({width:1440,height:1000});
  const preserved=await page.evaluate(()=>JSON.stringify(window.duckflyTelemetry.scene));
  await page.locator('#back-home').click();await page.locator('[data-scenario="flock"]').click();
  await page.getByRole('button',{name:'Continue →',exact:true}).click();
  await wizard.locator('#setup-duck-select').selectOption('duck-2');
  await wizard.locator('#setup-forward').selectOption('look-left');
  check(await wizard.locator('[data-rule="brain-forward-1"]').count()===1,'Second duck did not receive its connection');
  await wizard.locator('#setup-turn').selectOption('stop');
  check(await wizard.locator('[data-rule^="brain-turn-"]').count()===2,'Reassigning steering did not preserve both signal directions');
  check(await wizard.locator('[data-rule="brain-turn-1"] [data-connection="trigger"]').inputValue()==='left'&&await wizard.locator('[data-rule="brain-turn-2"] [data-connection="trigger"]').inputValue()==='right','Steering conversion lost a direction');
  await wizard.locator('#setup-duck-select').selectOption('duck-1');
  check(await wizard.locator('#setup-forward').inputValue()==='walk'&&await wizard.locator('[data-rule="brain-forward-1"]').count()===0,'A connection leaked to another duck');
  await wizard.getByRole('button',{name:'Close setup and discard changes'}).click();
  check(await page.evaluate(()=>JSON.stringify(window.duckflyTelemetry.scene))===preserved,'Cancelling the wizard changed the running scene');
  checks.push({name:'manual mode, mobile layouts, independent ducks and cancellation',passed:true});
  check(!errors.length,'Browser errors: '+errors.join('; '));
  return {format:'duckfly-simple-connections-browser',origin,checks,errors,passed:true};
}
