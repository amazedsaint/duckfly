async page => {
  const check=(condition,message)=>{if(!condition)throw Error(message);},receipts=[],errors=[];
  page.on('pageerror',error=>errors.push(error.message));
  await page.goto(await page.evaluate(()=>location.origin));
  await page.setViewportSize({width:1280,height:900});
  await page.waitForFunction(()=>window.duckflyTelemetry?.ready,null,{timeout:60000});
  await page.getByRole('button',{name:'Open studio',exact:true}).click();
  await page.locator('[data-scenario="vision"]').click();
  for(let step=0;step<3;step++)await page.getByRole('button',{name:'Continue →',exact:true}).click();
  await page.getByRole('button',{name:'Start scene',exact:true}).click();
  await page.waitForFunction(()=>window.duckflyTelemetry.time>2,null,{timeout:30000});
  await page.getByRole('button',{name:'Ⅱ Pause',exact:true}).click();
  await page.waitForFunction(()=>window.duckflyTelemetry.paused);
  const before=await page.evaluate(()=>JSON.stringify({time:window.duckflyTelemetry.time,branch:window.duckflyTelemetry.branch,agents:window.duckflyTelemetry.agents,ducks:window.duckflyTelemetry.ducks}));
  await page.getByRole('button',{name:'Why?',exact:true}).click();
  await page.waitForFunction(()=>!document.querySelector('#event-image').hidden);
  const selection=await page.evaluate(()=>({tick:window.duckflyTelemetry.tick,text:document.querySelector('#event-time').textContent,status:document.querySelector('#event-image-status').textContent}));
  check(selection.text.includes('tick '+selection.tick),'Inspector selected a different latest tick');
  check(selection.status.includes('eyes:duck-1'),'Inspector did not retain the selected duck camera');
  await page.locator('#event-eye').selectOption('left');
  const left=await page.locator('#event-image').evaluate(canvas=>Array.from(canvas.getContext('2d').getImageData(0,0,96,64).data));
  await page.locator('#event-eye').selectOption('right');
  const right=await page.locator('#event-image').evaluate(canvas=>Array.from(canvas.getContext('2d').getImageData(0,0,96,64).data));
  check(left.some((value,i)=>value!==right[i]),'Stereo selector shows the same camera for both eyes');
  await page.locator('#event-index').fill('0');
  await page.waitForFunction(()=>!document.querySelector('#event-image').hidden);
  const old=await page.locator('#event-time').textContent();
  check(old!==selection.text,'Recorded timeline failed to move to an earlier action');
  check(await page.evaluate(()=>JSON.stringify({time:window.duckflyTelemetry.time,branch:window.duckflyTelemetry.branch,agents:window.duckflyTelemetry.agents,ducks:window.duckflyTelemetry.ducks}))===before,'Inspection changed physical or neural state');
  receipts.push({check:'recorded action inspection and stereo preserve paused body state',latest:selection,earliest:old});
  await page.locator('#event-index').fill(await page.locator('#event-index').getAttribute('max'));
  await page.waitForFunction(()=>!document.querySelector('#event-image').hidden);
  await page.screenshot({path:'output/playwright/action-inspector-desktop.png'});
  await page.setViewportSize({width:390,height:844});
  const mobile=await page.locator('#event-dialog').evaluate(element=>({width:element.getBoundingClientRect().width,overflow:element.scrollWidth-element.clientWidth}));
  check(mobile.width<=390&&mobile.overflow<=1,'Action inspector overflows mobile');
  await page.screenshot({path:'output/playwright/action-inspector-mobile.png'});
  receipts.push({check:'mobile recorded inspector',...mobile});
  await page.getByRole('button',{name:'Close action inspector'}).click();
  await page.setViewportSize({width:1280,height:900});
  // Export through the real UI, then compare displayed pixels with its packet.
  await page.evaluate(()=>{const original=URL.createObjectURL;URL.createObjectURL=function(blob){if(blob.type.includes('json'))window.actionRecordingPromise=blob.text().then(JSON.parse);return original.call(this,blob);};});
  const advanced=page.getByRole('button',{name:'Advanced',exact:true});
  if(await advanced.getAttribute('aria-expanded')!=='true')await advanced.click();
  if(!await page.locator('#recordings-panel').evaluate(element=>element.open))await page.locator('#recordings-panel > summary').click();
  await page.getByRole('button',{name:'Export recording',exact:true}).click();
  await page.waitForFunction(()=>!!window.actionRecordingPromise);
  await page.evaluate(async()=>window.actionRecording=await window.actionRecordingPromise);
  await page.getByRole('button',{name:'Why?',exact:true}).click();
  await page.locator('#event-eye').selectOption('right');
  await page.waitForFunction(()=>!document.querySelector('#event-image').hidden);
  const matched=await page.evaluate(()=>{
    const recording=window.actionRecording,event=recording.events.at(-1),capture=event.causes[0].vision.capture;
    const packet=recording.frames.flatMap(([,frames])=>Object.values(frames)).find(frame=>frame.sourceId===capture.sourceId&&frame.frameId===capture.frameId&&frame.captureTime===capture.captureTime);
    const pixels=Uint8Array.from(atob(packet.views.right),c=>c.charCodeAt(0));
    const actual=document.querySelector('#event-image').getContext('2d').getImageData(0,0,96,64).data;
    return {equal:pixels.every((value,i)=>value===actual[i]),comparedValues:pixels.length,frameId:capture.frameId};
  });
  check(matched.equal,'Inspector image differs from the exported consumed camera frame');receipts.push({check:'exact exported frame comparison',...matched});
  await page.getByRole('button',{name:'Close action inspector'}).click();
  // The inspector must not implicitly pause a running scene.
  await page.getByRole('button',{name:'▶ Run',exact:true}).click();
  const start=await page.evaluate(()=>window.duckflyTelemetry.time);
  await page.getByRole('button',{name:'Why?',exact:true}).click();
  await page.waitForFunction(time=>window.duckflyTelemetry.time>time+.3,start,{timeout:10000});
  const running=await page.evaluate(()=>({paused:window.duckflyTelemetry.paused,time:window.duckflyTelemetry.time,selection:document.querySelector('#event-index').value}));
  check(!running.paused,'Inspecting an action paused the running world');receipts.push({check:'running world continues while recorded action remains selected',...running});
  await page.getByRole('button',{name:'Close action inspector'}).click();
  await page.getByRole('button',{name:'Ⅱ Pause',exact:true}).click();
  await page.waitForFunction(()=>window.duckflyTelemetry.paused);
  check(!errors.length,'Browser errors: '+errors.join('; '));
  const report={format:'duckfly-action-inspector-acceptance',receipts,pageErrors:errors};
  await page.evaluate(report=>window.duckflyActionAcceptance=report,report);
  return report;
}
